#!/usr/bin/env python3
"""Generate the operator's terminal theme (Ghostty + tmux + Claude Code status line) from arc_brand.json.

Theme "D + L4", approved 2026-09-29 on the Terminal Contact Sheet:
  - Ghostty: module ground, left translucent by the Ghostty config (background-opacity/blur live there).
  - tmux: the bracket status bar. Section rule on the leading edge, label in the section colour,
    value in an ink cap. Signal roles from screen._roles: IN blue, OPERATE orange, MONITOR green,
    OUT crimson. The red accent is never used (mark, LIVE and danger only).
  - Claude Code status line: colour variables sourced by ~/.claude/statusline.sh.

Every colour is resolved from the brand file. Rerun after any change to arc_brand.json:
    python3 ~/projects/arc-style/tools/gen_terminal_theme.py            # write + report
    python3 ~/projects/arc-style/tools/gen_terminal_theme.py --dry-run  # show what would change
then `tmux source-file ~/.tmux.conf` and reload Ghostty (cmd+shift+,).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "brand"))
import arc_brand  # noqa: E402

HOME = Path.home()
GHOSTTY_THEME = HOME / ".config/ghostty/themes/ARC Screen"
TMUX_THEME = HOME / ".tmux/arc-theme.conf"
CLAUDE_COLORS = HOME / ".claude/statusline-colors.sh"
TMUX_COLORS = HOME / ".tmux/arc-colors.sh"

STAMP = "GENERATED by arc-style/tools/gen_terminal_theme.py from arc-style/brand/arc_brand.json. Do not edit; rerun the generator."


def s(key: str) -> str:
    return arc_brand.hex(f"screen.{key}")


def ghostty() -> str:
    # ANSI slots. The brand has no cyan, so cyan falls back to secBlue (decided 2026-09-29).
    palette = [
        s("subGroup"), s("secRed"), s("secGreen"), s("warn"),
        s("secBlue"), s("secCrimson"), s("secBlue"), s("text1"),
        s("text2"), s("secRed"), s("live"), s("warn"),
        s("secBlue"), s("secCrimson"), s("secBlue"), s("text0"),
    ]
    lines = [f"# {STAMP}", f"background = {s('moduleBg')}", f"foreground = {s('text0')}",
             f"cursor-color = {s('text0')}", f"cursor-text = {s('ink')}",
             f"selection-background = {s('subGroup')}", f"selection-foreground = {s('text0')}"]
    lines += [f"palette = {i}={c}" for i, c in enumerate(palette)]
    return "\n".join(lines) + "\n"


def tmux() -> str:
    M, P, INK, SUB, LINE = s("moduleBg"), s("panelBg"), s("ink"), s("subGroup"), s("line")
    T0, T1, T2 = s("text0"), s("text1"), s("text2")
    BLUE, ORANGE, GREEN, CRIMSON, RED = s("secBlue"), s("secOrange"), s("secGreen"), s("secCrimson"), s("secRed")
    seg = "~/.tmux/scripts/arc-seg.sh"
    path = '"#{pane_current_path}"'
    # Claude Code's process reports its version (e.g. 2.1.284) as the command name; show "claude" instead.
    cmd = "#{?#{m/r:^[0-9]+[.][0-9.]+$,#{pane_current_command}},claude,#{pane_current_command}}"

    def bracket(colour: str, label: str, value: str, cap: str) -> str:
        v = f"#[nobold,fg={T0}]{value} " if value else ""
        return (f"#[bg={P},fg={colour}]▌#[bold]{label} {v}"
                f"#[bg={INK},fg={T0},bold] {cap} #[bg={M},nobold] ")

    sess = f"#{{?client_prefix,#[bg={ORANGE}#,fg={INK}],#[bg={SUB}#,fg={T0}]}}#[bold] #S #[bg={M},nobold] "
    line0 = (f"#[bg={M}]" + sess
             + bracket(BLUE, "IN", f"#({seg} in {path})", "#{b:pane_current_path}")
             + bracket(ORANGE, "OPERATE", "", f"#({seg} op)")
             + "#[align=right]"
             + bracket(GREEN, "MONITOR", f"#({seg} mon)", f"#({seg} net)")
             + bracket(CRIMSON, "OUT", f"#({seg} outv {path})", f"#({seg} outcap {path})")
             + f"#[fg={T1}]%H:%M #[fg={T2}]%m/%d ")
    sep = f" #[fg={LINE}]▐#[fg={T1}] "
    line1 = (f"#[bg={INK},fg={T2}] prefix C-a  s sessions · a activity · d dev  "
             f"#(~/.tmux/scripts/claude-states.sh)"
             f"#[align=right]#[fg={T1}]#(~/.tmux/scripts/network-dual.sh){sep}"
             f"#(~/.tmux/scripts/memory-status.sh){sep}#(~/.tmux/scripts/cpu-status.sh) "
             # continuum auto-save hooks status-right, which this bar never draws; drive it here.
             f"#(~/.tmux/plugins/tmux-continuum/scripts/continuum_save.sh)")

    q = lambda x: "'" + x.replace("'", "'\\''") + "'"  # noqa: E731
    out = [
        f"# {STAMP}",
        "set -g status 2",
        "set -g status-interval 5",
        f"set -g status-style {q(f'bg={M},fg={T0}')}",
        f"set -g status-format[0] {q(line0)}",
        f"set -g status-format[1] {q(line1)}",
        "",
        "# Pane borders: active = OPERATE (where your hands are), inactive = rule. bg=default keeps Ghostty translucency.",
        "set -g pane-border-lines heavy",
        "set -g pane-border-status top",
        f"set -g pane-border-format {q(f' #[fg={T1}]#{{pane_index}}: {cmd} #[fg={LINE}]│ #[fg={BLUE}]#{{pane_current_path}} ')}",
        f"set -g pane-border-style {q(f'fg={LINE},bg=default')}",
        f"set -g pane-active-border-style {q(f'fg={ORANGE},bg=default,bold')}",
        "",
        "# Names: windows and Ghostty tab titles read 'arc · claude', not '3' / '2.1.284'.",
        "setw -g automatic-rename on",
        f"setw -g automatic-rename-format {q(cmd)}",
        "set -g set-titles on",
        f"set -g set-titles-string {q('#S · ' + cmd)}",
        "",
        f"set -g message-style {q(f'bg={SUB},fg={T0}')}",
        f"set -g message-command-style {q(f'bg={SUB},fg={T0}')}",
        f"set -g mode-style {q(f'bg={SUB},fg={T0}')}",
        f"set -g window-status-style {q(f'bg={M},fg={T2}')}",
        f"set -g window-status-current-style {q(f'bg={SUB},fg={T0},bold')}",
        f"set -g window-status-activity-style {q(f'bg={M},fg={BLUE}')}",
        f"set -g window-status-bell-style {q(f'bg={M},fg={RED}')}",
        f"set -g display-panes-active-colour {q(ORANGE)}",
        f"set -g display-panes-colour {q(T2)}",
        f"setw -g clock-mode-colour {q(ORANGE)}",
        "",
        "# Claude activity feed: prefix + a toggles a strip along the bottom of the window.",
        "bind a run-shell '~/.tmux/scripts/activity-toggle.sh \"#{window_id}\" \"#{pane_current_path}\"'",
        "",
        "# Session switcher (L4): prefix + s. Built-in tree with preview; press f to filter, x to kill.",
        f"bind s choose-tree -Zs -O name -F {q('#{?pane_format,' + cmd + ' #{pane_current_path},#{?window_format,#{window_name},#{session_windows}w#{?session_attached, · attached,}}}')}",
    ]
    return "\n".join(out) + "\n"


def claude_colors() -> str:
    def esc(key: str) -> str:
        r, g, b = arc_brand.rgb255(f"screen.{key}")
        return f"$'\\e[38;2;{r};{g};{b}m'"
    names = {"TXT": "text0", "SUB": "text1", "DIM": "line", "IN": "secBlue", "OP": "secOrange",
             "MON": "secGreen", "OUT": "secCrimson", "LIVE": "live", "WARN": "warn", "BAD": "secRed"}
    return "\n".join([f"# {STAMP}"] + [f"{k}={esc(v)}" for k, v in names.items()]) + "\n"


def tmux_colors() -> str:
    """Hex colours for tmux #() scripts that emit their own #[fg=...] styles (claude-states.sh)."""
    names = {"TXT": "text0", "SUB": "text1", "DIM": "text2", "LINE": "line", "LIVE": "live", "WARN": "warn", "OP": "secOrange"}
    return "\n".join([f"# {STAMP}"] + [f"{k}='{s(v)}'" for k, v in names.items()]) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true", help="report changes without writing")
    args = ap.parse_args()
    changed = 0
    for path, text in ((GHOSTTY_THEME, ghostty()), (TMUX_THEME, tmux()), (CLAUDE_COLORS, claude_colors()), (TMUX_COLORS, tmux_colors())):
        old = path.read_text() if path.exists() else None
        state = "unchanged" if old == text else ("new" if old is None else "changed")
        print(f"{state:9} {path}")
        if state != "unchanged":
            changed += 1
            if not args.dry_run:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if changed and not args.dry_run:
        print("Reload: tmux source-file ~/.tmux.conf ; Ghostty cmd+shift+,")
    return 0


if __name__ == "__main__":
    sys.exit(main())
