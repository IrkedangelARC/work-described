"""Audit of the legacy per-job tools copied into arc-talk-edit/legacy/ (P0.4).

The copies are byte-identical to the job folders' tools (md5 checked here) and are kept as reference implementations;
P1+ stages replace them. Their hard-coded numbers and paths are extracted by AST (no import, so no Resolve side
effects) and checked against the job.yaml files by tests/test_legacy_constants.py.

Usage: python3 -m arc_talk_edit.legacy_audit   -> writes legacy/MANIFEST.md
"""
from __future__ import annotations
import ast, hashlib
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
LEGACY = PKG / "legacy"
PROJECTS = PKG.parent
SOURCES = {  # legacy dir -> (origin dir, job.yaml or None)
    "job_b": (PROJECTS / "talk-b-edit" / "tools", PKG / "jobs" / "job_b.yaml"),
    "job_a": (PROJECTS / "talk-a-edit" / "tools", PKG / "jobs" / "job_a.yaml"),
    "job_c": (PROJECTS / "talk-c-edit", None),
    "job_d": (PROJECTS / "talk-d-edit" / "tools", None),
}
CLOCK_NAMES = {"OFF", "FR_OFF", "OFFSET", "AJA_OFF", "SQ_OFF"}


def md5(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest()


def constants(p: Path) -> dict:
    """Module-level NAME = literal (numbers, and strings that are absolute paths). Tuple targets unpacked."""
    out = {}
    if p.suffix != ".py":
        return out
    tree = ast.parse(p.read_text(errors="replace"))
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for tgt in node.targets:
            pairs = []
            if isinstance(tgt, ast.Name):
                pairs = [(tgt.id, node.value)]
            elif isinstance(tgt, ast.Tuple) and isinstance(node.value, ast.Tuple) and len(tgt.elts) == len(node.value.elts):
                pairs = [(t.id, v) for t, v in zip(tgt.elts, node.value.elts) if isinstance(t, ast.Name)]
            for name, val in pairs:
                try:
                    v = ast.literal_eval(val)
                except Exception:
                    if isinstance(val, ast.BinOp):          # e.g. 60000 / 1001
                        try:
                            v = eval(compile(ast.Expression(val), "<c>", "eval"), {"__builtins__": {}})
                        except Exception:
                            continue
                    else:
                        continue
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    out[name] = v
                elif isinstance(v, str) and v.startswith(("/Volumes/", "/Users/", "/Library/")):
                    out[name] = v
    return out


def docline(p: Path) -> str:
    if p.suffix == ".py":
        try:
            d = ast.get_docstring(ast.parse(p.read_text(errors="replace"))) or ""
        except SyntaxError:
            d = ""
    else:
        d = " ".join(l.lstrip("# ").strip() for l in p.read_text(errors="replace").splitlines()[1:4] if l.startswith("#"))
    return " ".join(d.split())[:150]


def audit() -> list[dict]:
    rows = []
    for key, (origin, job) in SOURCES.items():
        for f in sorted((LEGACY / key).iterdir()):
            if f.suffix not in (".py", ".sh"):
                continue
            src = origin / f.name
            rows.append({"job": key, "file": f.name, "md5": md5(f), "identical": src.exists() and md5(src) == md5(f),
                         "origin": str(src), "doc": docline(f), "consts": constants(f), "yaml": job})
    return rows


def write_manifest(rows: list[dict]) -> Path:
    out = LEGACY / "MANIFEST.md"
    lines = ["# Legacy tools manifest (generated by `python3 -m arc_talk_edit.legacy_audit`; do not edit)", "",
             "Byte-identical copies of each job's tools, kept as reference implementations until the P1+ stages replace them.",
             "`identical` = md5 matches the job folder's copy at generation time. Constants are module-level literals",
             "(numbers and absolute paths) checked against job.yaml by tests/test_legacy_constants.py.", ""]
    for key in SOURCES:
        sub = [r for r in rows if r["job"] == key]
        lines += [f"## {key} ({len(sub)} files, origin `{SOURCES[key][0].relative_to(PROJECTS)}`)", "",
                  "| File | Same as origin | What | Hard-coded |", "|---|---|---|---|"]
        for r in sub:
            c = ", ".join(f"{k}={v}" for k, v in r["consts"].items() if not isinstance(v, str))
            paths = sum(isinstance(v, str) for v in r["consts"].values())
            c += (f"{'; ' if c else ''}{paths} path(s)" if paths else "")
            lines.append(f"| `{r['file']}` | {'yes' if r['identical'] else '**NO**'} | {r['doc'].replace('|', '/')} | {c} |")
        lines.append("")
    out.write_text("\n".join(lines) + "\n")
    return out


if __name__ == "__main__":
    rows = audit()
    p = write_manifest(rows)
    bad = [r["file"] for r in rows if not r["identical"]]
    print(f"{len(rows)} legacy files, {len(rows) - len(bad)} identical to origin; manifest {p}")
    if bad:
        print("NOT identical:", bad)
